    public function run(): void
    {
        if (app()->environment('production')) {
            throw new RuntimeException('SpeakerSeeder embeds archived production data and cannot run in production.');
        }

        OwnerContext::withOwner(null, function (): void {
            DB::transaction(function (): void {
                foreach (self::SPEAKERS as $speaker) {
                    $person = $this->importSpeaker($speaker);
                    $this->importNames($speaker, $person);
                    $this->importTitles($speaker, $person);
                    $this->importAddress($speaker, $person);
                    $this->importSocialProfiles($speaker, $person);
                    $this->importSearchTerms($speaker, $person);
                    $this->importSlugRedirects($speaker, $person);
                    $this->importEventLinks($speaker, $person);
                }
            });
        });

        $this->command?->table(
            ['Seeded data', 'Count'],
            [
                ['Speakers created as Person records', $this->createdSpeakerCount],
                ['Addresses created', $this->createdAddressCount],
                ['Social profiles created', $this->createdSocialProfileCount],
                ['Search terms created', $this->createdSearchTermCount],
                ['Slug redirects created', $this->createdRedirectCount],
                ['Matching local event links created', $this->createdEventLinkCount],
                ['Addresses skipped (country not seeded)', $this->skippedAddressCount],
                ['Event links skipped (event not seeded locally)', $this->skippedEventLinkCount],
                ['Social profiles skipped (unsupported platform)', $this->skippedSocialPlatformCount],
            ],
        );
    }

    /**
     * @param  array<string, mixed>  $speaker
     */
    private function importSpeaker(array $speaker): Person
    {
        $name = trim((string) $speaker['name']);

        $person = Person::query()->whereKey($speaker['id'])->first();

        if ($person instanceof Person) {
            $person->forceFill([
                'name' => $name !== '' ? $name : $person->name,
                'gender' => $speaker['gender'],
                'bio' => $this->normalizedBio($speaker['bio']),
                'status' => $this->personStatus((string) $speaker['status']),
                'speaker_status' => $speaker['is_active']
                    ? SpeakerStatus::Active->value
                    : SpeakerStatus::Inactive->value,
                'allow_public_event_submission' => (bool) $speaker['allow_public_event_submission'],
                'public_submission_locked_at' => $speaker['public_submission_locked_at'],
                'public_submission_locked_by' => null,
                'verified_at' => $speaker['status'] === 'verified'
                    ? ($person->verified_at ?? $speaker['created_at'])
                    : null,
                'rejected_at' => $speaker['status'] === 'rejected'
                    ? ($person->rejected_at ?? $speaker['updated_at'])
                    : null,
                'last_state_change_at' => $person->last_state_change_at ?? $speaker['updated_at'],
            ]);
            $person->saveQuietly();

            return $person;
        }

        $person = new Person;
        $person->forceFill([
            'id' => $speaker['id'],
            'name' => $name !== '' ? $name : 'Imported speaker',
            'slug' => $this->uniqueSlug((string) $speaker['slug']),
            'gender' => $speaker['gender'],
            'bio' => $this->normalizedBio($speaker['bio']),
            'searchable_name' => $speaker['searchable_name'],
            'status' => $this->personStatus((string) $speaker['status']),
            'verified_at' => $speaker['status'] === 'verified' ? $speaker['created_at'] : null,
            'rejected_at' => $speaker['status'] === 'rejected' ? $speaker['updated_at'] : null,
            'last_state_change_at' => $speaker['updated_at'],
            'speaker_status' => $speaker['is_active']
                ? SpeakerStatus::Active->value
                : SpeakerStatus::Inactive->value,
            'allow_public_event_submission' => (bool) $speaker['allow_public_event_submission'],
            'public_submission_locked_at' => $speaker['public_submission_locked_at'],
            'public_submission_locked_by' => null,
            'created_at' => $speaker['created_at'],
            'updated_at' => $speaker['updated_at'],
        ]);
        $person->saveQuietly();

        $this->createdSpeakerCount++;

        return $person;
    }

    private function uniqueSlug(string $slug): string
    {
        $baseSlug = Str::slug($slug) ?: 'speaker';
        $candidate = $baseSlug;
        $suffix = (string) Str::afterLast($baseSlug, '-');
        $attempt = 0;

        while (Person::query()->where('slug', $candidate)->exists()) {
            $attempt++;
            $candidate = $baseSlug.'-'.$suffix.($attempt > 1 ? '-'.$attempt : '');
        }

        return $candidate;
    }

    private function personStatus(string $sourceStatus): string
    {
        return match ($sourceStatus) {
            'verified', 'pending', 'rejected', 'inactive' => $sourceStatus,
            default => 'pending',
        };
    }

    /**
     * @param  array<string, mixed>  $speaker
     */
    private function importNames(array $speaker, Person $person): void
    {
        $name = trim((string) $speaker['name']);

        if ($name !== '') {
            $this->firstOrCreateName($person, PersonNameType::Display, $name, true);
        }

        $qualifiedName = trim(implode(' ', array_filter([
            ...array_map($this->formatTitle(...), $speaker['honorific']),
            ...array_map($this->formatTitle(...), $speaker['pre_nominal']),
            $name,
            ...array_map($this->formatTitle(...), $speaker['post_nominal']),
        ])));

        if ($qualifiedName !== '' && $qualifiedName !== $name) {
            $this->firstOrCreateName($person, PersonNameType::Professional, $qualifiedName);
        }
    }

    private function firstOrCreateName(Person $person, PersonNameType $type, string $fullName, bool $isPrimary = false): void
    {
        $fullName = trim($fullName);

        if ($fullName === '') {
            return;
        }

        $personName = PersonName::query()->firstOrCreate(
            [
                'person_id' => $person->getKey(),
                'name_type' => $type->value,
                'full_name' => $fullName,
                'language_code' => 'ms',
            ],
            ['is_primary' => $isPrimary],
        );

        if ($isPrimary && ! $personName->is_primary) {
            $personName->is_primary = true;
            $personName->save();
        }
    }

    private function formatTitle(mixed $title): string
    {
        if (! is_string($title)) {
            return '';
        }

        $title = trim($title);
        $key = Str::lower(str_replace(' ', '_', $title));

        return self::TITLE_ALIASES[$key] ?? $title;
    }

    /**
     * @param  array<string, mixed>  $speaker
     */
    private function importTitles(array $speaker, Person $person): void
    {
        $titles = [];

        foreach (['honorific', 'pre_nominal', 'post_nominal'] as $field) {
            foreach ($speaker[$field] as $sourceTitle) {
                $titleName = $this->formatTitle($sourceTitle);

                if ($titleName !== '') {
                    $titles[$titleName] = true;
                }
            }
        }

        foreach (array_keys($titles) as $titleName) {
            $title = Title::query()
                ->where(function ($query) use ($titleName): void {
                    $query->where('name', $titleName)
                        ->orWhere('short_form', $titleName);
                })
                ->orderBy('name')
                ->first();

            if (! $title instanceof Title) {
                continue;
            }

            TitleAssignment::query()->firstOrCreate(
                [
                    'titleable_type' => $person->getMorphClass(),
                    'titleable_id' => $person->getKey(),
                    'title_id' => $title->getKey(),
                ],
                ['status' => AssignmentStatus::Active->value],
            );
        }
    }

    /**
     * @param  array<string, mixed>  $speaker
     */
    private function importAddress(array $speaker, Person $person): void
    {
        $sourceAddress = $speaker['address'];

        if (! is_array($sourceAddress)) {
            return;
        }

        $country = AddressCountry::query()->where('iso2', $sourceAddress['country'])->first();

        if (! $country instanceof AddressCountry) {
            $this->skippedAddressCount++;

            return;
        }

        $address = $person->primaryAddress('primary');

        if (! $address instanceof Address) {
            $addressId = (string) $sourceAddress['id'];

            if (DB::table(AddressingTableResolver::resolve('addresses'))->where('id', $addressId)->exists()) {
                $addressId = (string) Str::orderedUuid();
            }

            $address = new Address;
            $address->setAttribute('id', $addressId);
        }

        $address->forceFill([
            'country_id' => $country->getKey(),
            'state_id' => null,
            'city_id' => null,
            'label' => null,
            'line1' => null,
            'line2' => null,
            'city' => null,
            'state' => null,
            'postcode' => null,
            'country' => $country->name,
            'country_code' => $country->iso2,
            'latitude' => null,
            'longitude' => null,
            'google_maps_url' => null,
            'google_place_id' => null,
            'waze_url' => null,
            'created_at' => $sourceAddress['created_at'],
            'updated_at' => $sourceAddress['updated_at'],
        ]);
        $address->save();
        $person->attachAddress($address, type: 'primary', isPrimary: true);

        if ($address->wasRecentlyCreated) {
            $this->createdAddressCount++;
        }
    }

    /**
     * @param  array<string, mixed>  $speaker
     */
    private function importSocialProfiles(array $speaker, Person $person): void
    {
        foreach ($speaker['socials'] as $sourceProfile) {
            $platform = $this->socialPlatform((string) $sourceProfile['platform']);

            if ($platform === null) {
                $this->skippedSocialPlatformCount++;

                continue;
            }

            $socialProfile = SocialProfile::query()
                ->where('socialable_type', $person->getMorphClass())
                ->where('socialable_id', $person->getKey())
                ->whereRaw("metadata->>'production_speaker_source_id' = ?", [(string) $sourceProfile['id']])
                ->first();

            $socialProfile ??= SocialProfile::query()
                ->where('socialable_type', $person->getMorphClass())
                ->where('socialable_id', $person->getKey())
                ->where('platform', $platform)
                ->where('url', $sourceProfile['url'])
                ->first();

            $isNewProfile = ! $socialProfile instanceof SocialProfile;

            if (! $socialProfile instanceof SocialProfile) {
                $socialProfile = new SocialProfile;
                $socialProfile->setAttribute(
                    'id',
                    DB::table('social_profiles')->where('id', $sourceProfile['id'])->exists()
                        ? (string) Str::orderedUuid()
                        : (string) $sourceProfile['id'],
                );
            }

            $socialProfile->forceFill([
                'socialable_type' => $person->getMorphClass(),
                'socialable_id' => $person->getKey(),
                'platform' => $platform,
                'purpose' => 'general',
                'label' => $platform !== Str::lower(trim((string) $sourceProfile['platform']))
                    ? trim((string) $sourceProfile['platform'])
                    : null,
                'handle' => $sourceProfile['username'],
                'url' => $sourceProfile['url'],
                'is_primary' => false,
                'is_public' => true,
                'is_verified' => false,
                'sort_order' => (int) ($sourceProfile['order_column'] ?? 0),
                'metadata' => array_merge(
                    is_array($socialProfile->metadata) ? $socialProfile->metadata : [],
                    ['production_speaker_source_id' => (string) $sourceProfile['id']],
                ),
                'created_at' => $sourceProfile['created_at'],
                'updated_at' => $sourceProfile['updated_at'],
            ]);
            $socialProfile->save();

            if ($isNewProfile) {
                $this->createdSocialProfileCount++;
            }
        }
    }

    private function socialPlatform(string $sourcePlatform): ?string
    {
        $platform = match (Str::lower(trim($sourcePlatform))) {
            'twitter' => SocialPlatform::X->value,
            'wikipedia' => SocialPlatform::Website->value,
            default => Str::lower(trim($sourcePlatform)),
        };

        return SocialPlatform::tryFrom($platform)?->value;
    }

    /**
     * @param  array<string, mixed>  $speaker
     */
    private function importSearchTerms(array $speaker, Person $person): void
    {
        foreach ($speaker['search_terms'] as $term) {
            $term = Str::limit(trim((string) $term), 120, '');

            if ($term === '') {
                continue;
            }

            $exists = DB::table('person_search_terms')
                ->where('person_id', $person->getKey())
                ->where('term', $term)
                ->exists();

            if ($exists) {
                continue;
            }

            DB::table('person_search_terms')->insert([
                'id' => (string) Str::orderedUuid(),
                'person_id' => $person->getKey(),
                'term' => $term,
            ]);

            $this->createdSearchTermCount++;
        }
    }

    /**
     * @param  array<string, mixed>  $speaker
     */
    private function importSlugRedirects(array $speaker, Person $person): void
    {
        foreach ($speaker['redirects'] as $redirect) {
            $sourceSlug = (string) $redirect['source_slug'];
            $destinationSlug = (string) $person->slug;
            $sourcePath = $this->personPath($sourceSlug);
            $destinationPath = $this->personPath($destinationSlug);

            if ($sourcePath === $destinationPath) {
                continue;
            }

            $existing = DB::table('slug_redirects')->where('source_path', $sourcePath)->first();

            if ($existing !== null
                && ($existing->redirectable_type !== $person->getMorphClass()
                    || (string) $existing->redirectable_id !== (string) $person->getKey())) {
                continue;
            }

            $redirectId = $existing === null ? $redirect['id'] : $existing->id;

            if ($existing === null && DB::table('slug_redirects')->where('id', $redirectId)->exists()) {
                $redirectId = (string) Str::orderedUuid();
            }

            DB::table('slug_redirects')->updateOrInsert(
                ['source_path' => $sourcePath],
                [
                    'id' => $redirectId,
                    'redirectable_type' => $person->getMorphClass(),
                    'redirectable_id' => $person->getKey(),
                    'source_slug' => $sourceSlug,
                    'source_path' => $sourcePath,
                    'destination_slug' => $destinationSlug,
                    'destination_path' => $destinationPath,
                    'first_visited_at' => $redirect['first_visited_at'],
                    'last_redirected_at' => $redirect['last_redirected_at'],
                    'redirect_count' => $redirect['redirect_count'],
                    'created_at' => $redirect['created_at'],
                    'updated_at' => $redirect['updated_at'],
                ],
            );

            if ($existing === null) {
                $this->createdRedirectCount++;
            }
        }
    }

    private function personPath(string $slug): string
    {
        return (string) route('persons.show', ['person' => ltrim($slug, '/')], false);
    }

    /**
     * @param  array<string, mixed>  $speaker
     */
    private function importEventLinks(array $speaker, Person $person): void
    {
        foreach ($speaker['event_links'] as $sourceEventLink) {
            $event = Event::query()->where('slug', $sourceEventLink['event_slug'])->first();
            $role = EventKeyPersonRole::tryFrom((string) $sourceEventLink['role']);

            if (! $event instanceof Event || $role === null) {
                $this->skippedEventLinkCount++;

                continue;
            }

            $existing = EventKeyPerson::query()
                ->where('event_id', $event->getKey())
                ->where('involveable_type', $person->getMorphClass())
                ->where('involveable_id', $person->getKey())
                ->where('role_code', $role->value)
                ->exists();

            if ($existing) {
                continue;
            }

            $keyPerson = new EventKeyPerson;
            $keyPerson->forceFill([
                'event_id' => $event->getKey(),
                'involveable_type' => $person->getMorphClass(),
                'involveable_id' => $person->getKey(),
                'role_code' => $role->value,
                'status' => 'active',
                'visibility' => $sourceEventLink['is_public'] ? 'public' : 'private',
                'prominence' => '0',
                'is_featured' => false,
                'is_primary' => false,
                'sort_order' => (int) $sourceEventLink['order_column'],
                'display_name' => $sourceEventLink['name'],
                'notes' => $sourceEventLink['notes'],
                'created_at' => $sourceEventLink['created_at'],
                'updated_at' => $sourceEventLink['updated_at'],
            ]);
            $keyPerson->save();

            $this->createdEventLinkCount++;
        }
    }

    /**
     * @return array<string, string>|null
     */
    private function normalizedBio(mixed $bio): ?array
    {
        if (! is_string($bio) || trim($bio) === '') {
            return null;
        }

        return ['ms' => $bio];
    }
